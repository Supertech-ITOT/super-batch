import { View, Text, Image } from "@react-pdf/renderer";
import { format } from "date-fns";
import { PDFTheme, styles } from "./PDFStyles";

interface Props {
  title: string;
  subtitle?: string;
  companyName?: string;
  companyLogo?: string;
  generatedBy?: string;
  generatedByEmail?: string;
  generatedAt?: Date | string;
}

export function PDFHeader({
  title,
  subtitle,
  companyName = "Super Batch",
  companyLogo = "/superbatch-light.png",
  generatedBy,
  generatedByEmail,
  generatedAt = new Date(),
}: Props) {
  const date = format(new Date(generatedAt), "EEE, dd MMM yyyy, hh:mm a");

  return (
    <View style={{ marginBottom: 10 }}>
      {/* Company & Generation Details */}
      <View
        style={{
          flexDirection: "row",
          justifyContent: "space-between",
          alignItems: "flex-start",
        }}
      >
        {/* Company Details */}
        <View
          style={{
            width: 180,
            height: 50,
            flexShrink: 0,
            alignSelf: "flex-start",
            justifyContent: "flex-start",
            alignItems: "flex-start",
          }}
        >
          <Image
            src={companyLogo || "/superbatch-light.png"}
            style={{
              width: 180,
              height: 50,
              objectFit: "contain",
              objectPosition: "left",
            }}
          />
        </View>

        {/* Generated Details */}
        <View style={{ alignItems: "flex-end" }}>
          <Text style={{ fontSize: 8, fontWeight: "bold", color: PDFTheme.primary, letterSpacing: 1 }}>GENERATED BY</Text>
          <View style={{ borderRightWidth: 1, borderRightColor: PDFTheme.primary, paddingRight: 4, alignItems: "flex-end" }}>
            {generatedBy && <Text style={{ fontSize: 7, color: PDFTheme.foreground }}>{generatedBy}</Text>}
            {generatedByEmail && <Text style={{ fontSize: 7, color: PDFTheme.muted }}>{generatedByEmail}</Text>}
            {companyName && <Text style={{ fontSize: 7, color: PDFTheme.muted }}>{companyName}</Text>}
            <Text style={{ fontSize: 7, color: PDFTheme.muted }}>{date}</Text>
          </View>
        </View>
      </View>

      {/* Report Title */}
      <View style={{ marginTop: 8 }}>
        <Text
          style={{
            fontSize: 18,
            fontWeight: "bold",
            color: PDFTheme.primary,
          }}
        >
          {title}
        </Text>

        {subtitle && (
          <Text
            style={{
              fontSize: 8,
              color: PDFTheme.secondary,
              marginTop: 2,
            }}
          >
            {subtitle}
          </Text>
        )}
      </View>

      {/* Divider */}
      <View
        style={{
          borderBottomWidth: 1,
          borderBottomColor: PDFTheme.border,
          marginTop: 8,
        }}
      />
    </View>
  );
}
